"""Export the Xenon 2000 sound effects as one 8-bit PCM blob plus an FPL manifest.

Every WAV in the game's sounds directory is converted to mono, signed 8-bit
(2's complement) samples, optionally resampled, and concatenated.

Outputs:
    <out>/sounds.bin        int8 samples, all sounds back to back
    <out>/sounds.json       name, offset, length (samples) and rate per sound
    sound_manifest.fpl      FPL source: SOUND_<NAME> index constants and the
                            soundManifest array of Sample(offset, length)

Usage: python export_sounds.py [--out DIR] [--game DIR] [--manifest FILE] [--rate HZ]
    --rate HZ   resample to HZ (default: keep the original rate, 44100)
"""
import glob
import json
import os
import re
import sys
import wave

import numpy as np

GAME_DIR = r"C:\Program Files (x86)\The Bitmap Brothers\Xenon 2000 - Project PCF"


def read_wav(path):
    with wave.open(path) as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width == 1:
        x = (np.frombuffer(raw, np.uint8).astype(np.float64) - 128) / 128
    elif width == 2:
        x = np.frombuffer(raw, "<i2").astype(np.float64) / 32768
    else:
        raise ValueError(f"{path}: unsupported sample width {width}")
    return x.reshape(-1, ch).mean(axis=1), rate


def resample(x, src, dst):
    if src == dst:
        return x
    n = int(round(len(x) * dst / src))
    return np.interp(np.arange(n) * src / dst, np.arange(len(x)), x)


def to_int8(x):
    return np.clip(np.round(x * 128), -128, 127).astype(np.int8)


def const_name(stem):
    return "SOUND_" + re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_").upper()


def write_manifest(path, sounds):
    lines = ["# Generated by export_sounds.py - do not edit.",
             "# Sample(offset into sounds.bin, length in samples), one entry per sound.", "",
             "struct Sample(offset: Int, length: Int)", ""]
    for i, s in enumerate(sounds):
        lines.append(f"const {s['const']} = {i}")
    lines += ["", f"const NUM_SOUNDS = {len(sounds)}", "", "const soundManifest = const Array<Sample>["]
    for i, s in enumerate(sounds):
        sep = "," if i < len(sounds) - 1 else " ]"
        lines.append(f"    Sample({s['offset']}, {s['length']}){sep}".ljust(36) + f"# {s['name']}")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    argv = sys.argv[1:]
    here = os.path.dirname(os.path.abspath(__file__))
    opts = {"--out": "export", "--game": GAME_DIR, "--rate": None,
            "--manifest": os.path.join(here, "sound_manifest.fpl")}
    for opt in opts:
        if opt in argv:
            i = argv.index(opt)
            opts[opt] = argv[i + 1]
            del argv[i:i + 2]
    out, game = opts["--out"], opts["--game"]
    rate_out = int(opts["--rate"]) if opts["--rate"] else None

    files = sorted(glob.glob(os.path.join(game, "sounds", "*.wav")) +
                   glob.glob(os.path.join(game, "sounds", "*.WAV")), key=lambda p: os.path.basename(p).lower())
    files = list(dict.fromkeys(files))
    sounds, chunks, pos = [], [], 0
    for path in files:
        x, rate = read_wav(path)
        rate_dst = rate_out or rate
        data = to_int8(resample(x, rate, rate_dst))
        stem = os.path.splitext(os.path.basename(path))[0]
        sounds.append(dict(name=stem, const=const_name(stem), source=os.path.basename(path),
                           offset=pos, length=len(data), rate=rate_dst))
        chunks.append(data)
        pos += len(data)

    os.makedirs(out, exist_ok=True)
    blob = np.concatenate(chunks)
    blob.tofile(os.path.join(out, "sounds.bin"))
    with open(os.path.join(out, "sounds.json"), "w") as f:
        json.dump({"data": "sounds.bin", "format": "int8 mono", "sounds": sounds}, f, indent=2)
    write_manifest(opts["--manifest"], sounds)

    # Round-trip check from the written file
    back = np.fromfile(os.path.join(out, "sounds.bin"), np.int8)
    assert len(back) == pos and all(
        np.array_equal(back[s["offset"]:s["offset"] + s["length"]], c) for s, c in zip(sounds, chunks))
    print(f"{len(sounds)} sounds, {pos} bytes at {sounds[0]['rate']} Hz")
    print("written to", os.path.abspath(out))


if __name__ == "__main__":
    main()
